const $ = (sel) => document.querySelector(sel);
const md = (text) => DOMPurify.sanitize(marked.parse(text || ""));
const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

const store = {
  get id() { try { return localStorage.getItem("profileId"); } catch { return null; } },
  set id(v) { try { localStorage.setItem("profileId", v); } catch {} },
};
let row = null; // profile row from the API
let interviewId = null;

function toast(msg) {
  const t = $("#toast");
  t.textContent = msg;
  t.hidden = false;
  clearTimeout(toast.timer);
  toast.timer = setTimeout(() => (t.hidden = true), 4000);
}

async function api(path, body, isForm = false) {
  const opts = body === undefined ? {} : {
    method: "POST",
    body: isForm ? body : JSON.stringify(body),
    headers: isForm ? {} : { "Content-Type": "application/json" },
  };
  const res = await fetch(path, opts);
  const data = await res.json().catch(() => ({}));
  if (!res.ok) {
    // FastAPI validation errors arrive as a list.
    const detail = Array.isArray(data.detail) ? data.detail.map((d) => `${d.loc.at(-1)}: ${d.msg}`).join("; ") : data.detail;
    throw new Error(detail || `Request failed (${res.status})`);
  }
  return data;
}

async function busy(button, label, fn) {
  const original = button.textContent;
  button.disabled = true;
  button.textContent = label;
  try { await fn(); } catch (e) { toast(e.message); } finally {
    button.disabled = false;
    button.textContent = original;
  }
}

function show(view) {
  document.querySelectorAll(".view").forEach((v) => v.classList.toggle("active", v.id === `view-${view}`));
  document.querySelectorAll("#nav button").forEach((b) => b.classList.toggle("active", b.dataset.view === view));
  if (view !== "onboarding" && !row) {
    toast("Save your profile first.");
    return show("onboarding");
  }
}
document.querySelectorAll("#nav button").forEach((b) => b.addEventListener("click", () => show(b.dataset.view)));

function topics() {
  return (row?.roadmap?.weeks || []).flatMap((w) => w.topics.map((t) => ({ ...t, week: w.weekNumber })));
}

// ---------- Render ----------
function renderProfile() {
  if (!row) return;
  const p = row.profile;
  $("#who").textContent = `${p.targetRole} · ${p.targetCompanies.join(", ")}`;
  $("#company").innerHTML = (p.targetCompanies.length ? p.targetCompanies : ["a top tech company"])
    .map((c) => `<option>${esc(c)}</option>`).join("");

  const r = row.resume;
  $("#resume-summary").innerHTML = r ? `
    <div class="card">
      <h2>${esc(r.name)}</h2>
      <div class="chips">${(r.skills || []).map((s) => `<span class="chip">${esc(s)}</span>`).join("")}</div>
      ${(r.projects || []).map((pr) => `<div class="topic"><strong>${esc(pr.name)}</strong><p>${esc(pr.description)}</p></div>`).join("")}
    </div>` : "";
}

function renderRoadmap(source) {
  const weeks = row?.roadmap?.weeks;
  if (!weeks) {
    $("#roadmap").innerHTML = `<div class="empty">No roadmap yet. Generation takes a minute or two; the default is instant.</div>`;
    return;
  }
  $("#roadmap").innerHTML = (source ? `<p class="source">Source: ${source === "sarvam" ? "generated by Sarvam-105B" : "default roadmap"}</p>` : "") +
    weeks.map((w) => `
      <article class="card week">
        <div class="num">Week ${w.weekNumber}</div>
        <h3>${esc(w.focus)}</h3>
        ${w.topics.map((t) => `
          <div class="topic">
            <span class="tag ${esc(t.category.split(" ")[0])}">${esc(t.category)}</span>
            <strong>${esc(t.name)}</strong>
            <p>${esc(t.why)}</p>
          </div>`).join("")}
        <ol class="challenges">${(w.dailyChallenges || []).map((c) => `<li>${esc(c)}</li>`).join("")}</ol>
      </article>`).join("");
  // Keep the roadmap grid to one row on wide screens.
  $("#roadmap").style.gridTemplateColumns = window.innerWidth > 1000 ? `repeat(${weeks.length}, 1fr)` : "";

  $("#topic-select").innerHTML = topics()
    .map((t, i) => `<option value="${i}">Week ${t.week} · ${esc(t.name)} (${esc(t.category)})</option>`).join("");
}

function renderChat(messages, finished) {
  $("#chat").innerHTML = messages.map((m, i) => {
    const verdict = finished && i === messages.length - 1;
    return `<div class="msg ${m.role} ${verdict ? "verdict" : ""}">
      <div class="who-label">${m.role === "assistant" ? (verdict ? "Verdict" : "Interviewer") : "You"}</div>
      <div class="prose">${m.role === "assistant" ? md(m.content) : esc(m.content)}</div>
    </div>`;
  }).join("");
  $("#answer-form").hidden = finished;
  $("#chat").lastElementChild?.scrollIntoView({ behavior: "smooth", block: "start" });
}

// ---------- Actions ----------
$("#profile-form").addEventListener("submit", (e) => {
  e.preventDefault();
  const form = new FormData(e.target);
  if (!form.get("resume")?.size) form.delete("resume");
  busy(e.submitter, form.has("resume") ? "Reading resume…" : "Saving…", async () => {
    row = await api("/api/profile", form, true);
    store.id = row.id;
    renderProfile();
    renderRoadmap();
    toast(row.warning || "Profile saved.");
    show("roadmap");
  });
});

function loadRoadmap(button, useDefault) {
  busy(button, useDefault ? "Loading…" : "Generating (1–2 min)…", async () => {
    const res = await api("/api/roadmap", { profile_id: row.id, use_default: useDefault });
    row.roadmap = res.roadmap;
    renderRoadmap(res.source);
  });
}
$("#gen-roadmap").addEventListener("click", (e) => loadRoadmap(e.target, false));
$("#default-roadmap").addEventListener("click", (e) => loadRoadmap(e.target, true));

$("#explain").addEventListener("click", (e) => {
  const t = topics()[$("#topic-select").value];
  if (!t) return toast("Load a roadmap first.");
  busy(e.target, "Thinking…", async () => {
    const res = await api("/api/topic", { profile_id: row.id, topic: t.name, category: t.category });
    $("#topic-out").innerHTML = md(res.markdown);
  });
});

$("#review").addEventListener("click", (e) => {
  busy(e.target, "Reviewing…", async () => {
    const res = await api("/api/review", { problem: $("#problem").value, code: $("#code").value });
    $("#review-out").innerHTML = md(res.markdown);
  });
});

$("#start").addEventListener("click", (e) => {
  const t = topics()[$("#topic-select").value];
  busy(e.target, "Starting…", async () => {
    const res = await api("/api/interview", {
      profile_id: row.id, company: $("#company").value, kind: $("#kind").value, topic: t?.name,
    });
    interviewId = res.id;
    renderChat(res.messages, res.finished);
  });
});

$("#answer-form").addEventListener("submit", (e) => {
  e.preventDefault();
  const answer = $("#answer").value.trim();
  if (!answer) return;
  busy(e.submitter, "Sending…", async () => {
    const res = await api(`/api/interview/${interviewId}/reply`, { answer });
    $("#answer").value = "";
    renderChat(res.messages, res.finished);
  });
});

// ---------- Boot ----------
(async () => {
  renderRoadmap();
  if (!store.id) return;
  try {
    row = await api(`/api/profile/${store.id}`);
    renderProfile();
    renderRoadmap();
  } catch {
    // Stale id (e.g. in-memory store restarted); start fresh.
  }
})();
